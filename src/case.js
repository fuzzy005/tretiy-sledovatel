function textOf(value, n) {
  return typeof value === 'function' ? value(n) : value
}

export function suspectsFor(n) {
  return suspects
    .filter((item) => item.from <= n && (item.until == null || item.until >= n))
    .map((item) => ({
      id: item.id,
      name: textOf(item.name, n),
      role: textOf(item.role, n),
    }))
}

export function heatLabel(heat) {
  if (heat === 'hot') return 'Горячо'
  if (heat === 'warm') return 'Тепло'
  if (heat === 'neutral') return 'Рано'
  if (heat === 'cold') return 'Мимо'
  return 'Ложный след'
}

export function stepLabel(quality) {
  if (quality === 'right') return 'Такой шаг группа потом делает.'
  if (quality === 'side') return 'Шаг боковой: он про соседнее дело.'
  return 'Этот шаг уводит в сторону.'
}

export function evaluate(reports) {
  const rows = episodes.map((episode) => {
    const report = reports[episode.n]
    if (!report) return { n: episode.n, short: episode.short, missing: true }

    const theory = episode.theories.find((item) => item.id === report.theoryId)
    const step = episode.steps.find((item) => item.id === report.stepId)
    const suspect = suspectsFor(episode.n).find((item) => item.id === report.suspectId)
    const heat = theory?.heat ?? 'cold'
    const suspectHit = episode.correctSuspects.includes(report.suspectId)
    const score = (HEAT_SCORE[heat] ?? 0) + (suspectHit ? 2 : 0)

    return {
      n: episode.n,
      short: episode.short,
      missing: false,
      report,
      theory,
      step,
      suspect,
      heat,
      suspectHit,
      score,
    }
  })

  const answered = rows.filter((row) => !row.missing)
  let best = null
  for (const row of answered) {
    if (!best || row.score > best.score) best = row
  }
  const peaks = best ? answered.filter((row) => row.score === best.score) : []
  const falseLeads = answered.filter((row) => row.heat === 'false').map((row) => row.n)
  const hotCount = answered.filter((row) => row.heat === 'hot').length
  const hitCount = answered.filter((row) => row.suspectHit).length

  return { rows, best, peaks, falseLeads, hotCount, hitCount, filed: answered.length }
}

export function headline(result) {
  if (!result.best) return 'Рапортов пока нет.'
  const score = result.best.score
  const nums = result.peaks.map((row) => row.n).join(', ')
  if (result.peaks.length > 1 && score >= 3) {
    return `Вплотную вы подходили не раз: серии ${nums}. Самый ранний такой вечер — ${result.peaks[0].n}.`
  }
  if (score >= 5) return `Ближе всего к правде вы были на ${result.best.n} серии.`
  if (score >= 3) return `Ближе всего вы подошли на ${result.best.n} серии. Версия грелась, лицо ещё плавало.`
  return `До самого ключа версия так и не легла на след. Ближе остальных была ${result.best.n} серия.`
}

export function falseLeadLine(falseLeads) {
  if (falseLeads.length === 0) return 'На ложный след вы не свернули ни разу.'
  if (falseLeads.length === 1) return `Ложный след один: серия ${falseLeads[0]}.`
  return `Ложный след: серии ${falseLeads.join(', ')}.`
}

export function assertCase() {
  const errors = []
  if (episodes.length !== 8) errors.push('ожидалось 8 серий')
  const seen = new Set()
  for (const episode of episodes) {
    if (seen.has(episode.n)) errors.push(`повтор серии ${episode.n}`)
    seen.add(episode.n)
    if (episode.clues.length < 5) errors.push(`мало улик в серии ${episode.n}`)
    if (episode.theories.length !== 4) errors.push(`версии серии ${episode.n}`)
    if (episode.steps.length !== 4) errors.push(`шаги серии ${episode.n}`)
    const ids = new Set(suspectsFor(episode.n).map((item) => item.id))
    for (const id of episode.correctSuspects) {
      if (!ids.has(id)) errors.push(`серия ${episode.n}: подозреваемого ${id} нет в списке`)
    }
    const theoryIds = new Set()
    for (const theory of episode.theories) {
      if (theoryIds.has(theory.id)) errors.push(`серия ${episode.n}: повтор версии ${theory.id}`)
      theoryIds.add(theory.id)
      if (!theory.label || !theory.why || !(theory.heat in HEAT_SCORE)) {
        errors.push(`серия ${episode.n}: битая версия ${theory.id}`)
      }
    }
  }
  return errors
}
